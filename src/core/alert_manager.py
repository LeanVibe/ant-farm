logger = logging.getLogger(__name__)


@dataclass
class NotificationChannel:
    """Configuration for a notification channel."""
    id: str
    type: str  # "email", "slack", "webhook"
    name: str
    config: Dict[str, Any]
    enabled: bool = True
    filters: Dict[str, Any] = field(default_factory=dict)  # severity, metric filters


@dataclass
class AlertTemplate:
    """Template for formatting alerts."""
    name: str
    subject_template: str
    body_template: str
    channel_type: str


@dataclass
class EscalationRule:
    """Rule for escalating alerts."""
    id: str
    name: str
    conditions: Dict[str, Any]  # duration, severity, count
    channels: List[str]  # channel IDs to notify
    enabled: bool = True


class AlertManager:
    """Central alert management and notification system."""

