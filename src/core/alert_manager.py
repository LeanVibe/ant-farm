    def add_channel(self, channel: NotificationChannel):
        """Add a notification channel."""
        self.channels[channel.id] = channel
        logger.info(f"Added notification channel: {channel.name}")

    def remove_channel(self, channel_id: str):
        """Remove a notification channel."""
        if channel_id in self.channels:
            del self.channels[channel_id]
            logger.info(f"Removed notification channel: {channel_id}")

    def add_template(self, template: AlertTemplate):
        """Add an alert template."""
        self.templates[template.name] = template
        logger.info(f"Added alert template: {template.name}")

    def add_escalation_rule(self, rule: EscalationRule):
        """Add an escalation rule."""
        self.escalation_rules[rule.id] = rule
        logger.info(f"Added escalation rule: {rule.name}")

    async def process_alert(self, alert: Alert):
        """Process an incoming alert and send notifications."""
        try:
            # Check deduplication
            if self._is_duplicate_alert(alert):
                logger.info(f"Deduplicating alert: {alert.title}")
                return

            # Find matching channels
            matching_channels = self._find_matching_channels(alert)

            # Send notifications
            notification_tasks = []
            for channel in matching_channels:
                task = self._send_notification(alert, channel)
                notification_tasks.append(task)

            if notification_tasks:
                await asyncio.gather(*notification_tasks, return_exceptions=True)

            # Check escalation rules
            await self._check_escalation_rules(alert)

            # Record in history
            self._record_alert_history(alert)

        except Exception as e:
            logger.error(f"Error processing alert {alert.id}: {str(e)}")

    def _is_duplicate_alert(self, alert: Alert) -> bool:
        """Check if alert is a duplicate based on deduplication rules."""
        alert_key = f"{alert.metric_name}_{alert.severity.value}"
        last_notification = self.dedup_cache.get(alert_key, 0)

        # Don't send duplicate alerts within 5 minutes
        if time.time() - last_notification < 300:
            return True

        self.dedup_cache[alert_key] = time.time()
        return False

    def _find_matching_channels(self, alert: Alert) -> List[NotificationChannel]:
        """Find channels that match the alert criteria."""
        matching = []

        for channel in self.channels.values():
            if not channel.enabled:
                continue

            # Check severity filter
            min_severity = channel.filters.get("min_severity", "low")
            if not self._severity_matches(alert.severity, min_severity):
                continue

            # Check metric filter
            metric_filter = channel.filters.get("metrics", [])
            if metric_filter and alert.metric_name not in metric_filter:
                continue

            matching.append(channel)

        return matching

    def _severity_matches(self, alert_severity: Severity, min_severity: str) -> bool:
        """Check if alert severity meets minimum requirement."""
        severity_levels = {
            "low": 1,
            "medium": 2,
            "high": 3,
            "critical": 4
        }

        alert_level = severity_levels.get(alert_severity.value, 0)
        min_level = severity_levels.get(min_severity, 0)

        return alert_level >= min_level

    async def _send_notification(self, alert: Alert, channel: NotificationChannel):
        """Send notification through a specific channel."""
        try:
            if channel.type == "email":
                await self._send_email_notification(alert, channel)
            elif channel.type == "slack":
                await self._send_slack_notification(alert, channel)
            elif channel.type == "webhook":
                await self._send_webhook_notification(alert, channel)
            else:
                logger.warning(f"Unknown channel type: {channel.type}")

        except Exception as e:
            logger.error(f"Failed to send {channel.type} notification: {str(e)}")

    async def _send_email_notification(self, alert: Alert, channel: NotificationChannel):
        """Send email notification."""
        config = channel.config
        template = self.templates.get("email_default")

        if not template:
            logger.error("Email template not found")
            return

        # Format message
        subject = template.subject_template.format(
            severity=alert.severity.value.upper(),
            title=alert.title
        )

        body = template.body_template.format(
            severity=alert.severity.value.upper(),
            title=alert.title,
            description=alert.description,
            metric_name=alert.metric_name,
            current_value=alert.current_value,
            threshold_value=alert.threshold_value,
            created_at=time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(alert.created_at))
        )

        # Create message
        msg = MIMEMultipart("alternative")
        msg["Subject"] = subject
        msg["From"] = config["from_email"]
        msg["To"] = ", ".join(config["to_emails"])

        msg.attach(MIMEText(body, "html"))

        # Send email
        try:
            server = smtplib.SMTP(config["smtp_server"], config["smtp_port"])
            if config.get("username") and config.get("password"):
                server.starttls()
                server.login(config["username"], config["password"])

            server.sendmail(config["from_email"], config["to_emails"], msg.as_string())
            server.quit()

            logger.info(f"Email notification sent for alert: {alert.title}")

        except Exception as e:
            logger.error(f"Failed to send email: {str(e)}")

    async def _send_slack_notification(self, alert: Alert, channel: NotificationChannel):
        """Send Slack notification."""
        config = channel.config
        template = self.templates.get("slack_default")

        if not template or not config.get("webhook_url"):
            logger.error("Slack template or webhook URL not configured")
            return

        # Format message
        body = template.body_template.format(
            severity=alert.severity.value.upper(),
            title=alert.title,
            description=alert.description,
            metric_name=alert.metric_name,
            current_value=alert.current_value,
            threshold_value=alert.threshold_value,
            created_at=time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(alert.created_at))
        )

        payload = {
            "channel": config.get("channel", "#alerts"),
            "username": config.get("username", "LeanVibe Monitor"),
            "text": body,
            "icon_emoji": ":warning:"
        }

        # Send webhook
        async with aiohttp.ClientSession() as session:
            try:
                async with session.post(
                    config["webhook_url"],
                    json=payload,
                    timeout=aiohttp.ClientTimeout(total=10)
                ) as response:
                    if response.status == 200:
                        logger.info(f"Slack notification sent for alert: {alert.title}")
                    else:
                        logger.error(f"Slack webhook failed with status: {response.status}")

            except Exception as e:
                logger.error(f"Failed to send Slack notification: {str(e)}")

    async def _send_webhook_notification(self, alert: Alert, channel: NotificationChannel):
        """Send webhook notification."""
        config = channel.config

        if not config.get("url"):
            logger.error("Webhook URL not configured")
            return

        # Prepare payload
        payload = {
            "alert_id": alert.id,
            "title": alert.title,
            "description": alert.description,
            "severity": alert.severity.value,
            "metric_name": alert.metric_name,
            "current_value": alert.current_value,
            "threshold_value": alert.threshold_value,
            "created_at": alert.created_at,
            "status": alert.status.value,
            "metadata": alert.metadata
        }

        headers = config.get("headers", {})
        headers["Content-Type"] = "application/json"
        timeout = config.get("timeout", 10)

        # Send webhook
        async with aiohttp.ClientSession() as session:
            try:
                async with session.post(
                    config["url"],
                    json=payload,
                    headers=headers,
                    timeout=aiohttp.ClientTimeout(total=timeout)
                ) as response:
                    if response.status < 300:
                        logger.info(f"Webhook notification sent for alert: {alert.title}")
                    else:
                        logger.error(f"Webhook failed with status: {response.status}")

            except Exception as e:
                logger.error(f"Failed to send webhook notification: {str(e)}")

    async def _check_escalation_rules(self, alert: Alert):
        """Check if alert matches any escalation rules."""
        for rule in self.escalation_rules.values():
            if not rule.enabled:
                continue

            if self._matches_escalation_rule(alert, rule):
                # Send escalated notifications
                escalation_channels = [
                    self.channels[channel_id] for channel_id in rule.channels
                    if channel_id in self.channels
                ]

                escalation_tasks = []
                for channel in escalation_channels:
                    # Mark as escalated in metadata
                    escalated_alert = Alert(
                        id=f"{alert.id}_escalated",
                        title=f"🚨 ESCALATED: {alert.title}",
                        description=f"Escalated by rule '{rule.name}': {alert.description}",
                        severity=Severity.CRITICAL if alert.severity == Severity.HIGH else alert.severity,
                        metric_name=alert.metric_name,
                        current_value=alert.current_value,
                        threshold_value=alert.threshold_value,
                        status=alert.status,
                        created_at=time.time(),
                        metadata={**alert.metadata, "escalation_rule": rule.name}
                    )

                    task = self._send_notification(escalated_alert, channel)
                    escalation_tasks.append(task)

                if escalation_tasks:
                    await asyncio.gather(*escalation_tasks, return_exceptions=True)
                    logger.warning(f"Alert escalated by rule '{rule.name}': {alert.title}")

    def _matches_escalation_rule(self, alert: Alert, rule: EscalationRule) -> bool:
        """Check if alert matches escalation rule conditions."""
        conditions = rule.conditions

        # Check severity
        if "severity" in conditions:
            if alert.severity.value != conditions["severity"]:
                return False

        # Check duration (alert age)
        if "duration_minutes" in conditions:
            alert_age_minutes = (time.time() - alert.created_at) / 60
            if alert_age_minutes < conditions["duration_minutes"]:
                return False

        # Check count threshold (would need historical data)
        if "count_threshold" in conditions:
            # This would require tracking similar alerts
            # For now, just check if this is a repeated alert
            similar_alerts = [
                h for h in self.alert_history[-50:]  # Last 50 alerts
                if h["metric_name"] == alert.metric_name and
                time.time() - h["created_at"] < 3600  # Within last hour
            ]
            if len(similar_alerts) < conditions["count_threshold"]:
                return False

        return True

    def _record_alert_history(self, alert: Alert):
        """Record alert in history."""
        history_entry = {
            "alert_id": alert.id,
            "title": alert.title,
            "severity": alert.severity.value,
            "metric_name": alert.metric_name,
            "current_value": alert.current_value,
            "threshold_value": alert.threshold_value,
            "created_at": alert.created_at,
            "resolved_at": alert.resolved_at,
            "status": alert.status.value
        }

        self.alert_history.append(history_entry)

        # Keep only last 1000 entries
        if len(self.alert_history) > 1000:
            self.alert_history = self.alert_history[-1000:]

    def get_alert_history(self, limit: int = 100) -> List[Dict[str, Any]]:
        """Get recent alert history."""
        return self.alert_history[-limit:]

    def get_alert_stats(self) -> Dict[str, Any]:
        """Get alert statistics."""
        if not self.alert_history:
            return {"total_alerts": 0, "by_severity": {}, "by_metric": {}}

        stats = {
            "total_alerts": len(self.alert_history),
            "by_severity": {},
            "by_metric": {},
            "recent_alerts": len([a for a in self.alert_history[-100:] if time.time() - a["created_at"] < 3600])
        }

        for alert in self.alert_history:
            severity = alert["severity"]
            metric = alert["metric_name"]

            stats["by_severity"][severity] = stats["by_severity"].get(severity, 0) + 1
            stats["by_metric"][metric] = stats["by_metric"].get(metric, 0) + 1

        return stats

    def acknowledge_alert(self, alert_id: str):
        """Acknowledge an alert (for external systems)."""
        # This would typically update an external system
        logger.info(f"Alert acknowledged: {alert_id}")


